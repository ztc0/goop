import type { OemFiles } from "../types/windows-vm";

const ED25519_KEY = /^ssh-ed25519 [A-Za-z0-9+/]+={0,2}$/;

/**
 * The `type key` part of one ed25519 public key, without its comment, or undefined.
 * Only this validated form ever reaches setup.ps1.
 */
export function parsePublicKey(text: string): string | undefined {
  const lines = text.trim().split("\n");
  if (lines.length !== 1) return undefined;
  const [type, key] = (lines[0] ?? "").trim().split(/\s+/);
  const candidate = `${type} ${key}`;
  return ED25519_KEY.test(candidate) ? candidate : undefined;
}

/** A PowerShell single-quoted literal: a quote inside is doubled. */
function quote(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function windowsLines(lines: string[]): string {
  return `${lines.join("\r\n")}\r\n`;
}

/**
 * dockur copies /oem to C:\OEM and runs install.bat at the end of Windows setup. setup.ps1
 * enables OpenSSH with the VM key and writes C:\OEM\ready.txt last, so the marker means done.
 */
export function oemFiles(publicKey: string): OemFiles {
  const key = parsePublicKey(publicKey);
  if (key === undefined) throw new Error("Not an ed25519 public key");
  const installBat = windowsLines([
    "@echo off",
    "powershell -ExecutionPolicy Bypass -File C:\\OEM\\setup.ps1 > C:\\OEM\\setup.log 2>&1",
  ]);
  const setupPs1 = windowsLines([
    "# Generated by scripts/windows-vm: enables SSH access for the goop test VM.",
    "$ErrorActionPreference = 'Stop'",
    "Add-WindowsCapability -Online -Name OpenSSH.Server~~~~0.0.1.0",
    "Set-Service -Name sshd -StartupType Automatic",
    "Start-Service -Name sshd",
    "if (-not (Get-NetFirewallRule -Name goop-sshd -ErrorAction SilentlyContinue)) {",
    "  New-NetFirewallRule -Name goop-sshd -DisplayName 'goop OpenSSH Server' -Enabled True -Direction Inbound -Protocol TCP -Action Allow -LocalPort 22 | Out-Null",
    "}",
    "New-Item -Path 'HKLM:\\SOFTWARE\\OpenSSH' -Force | Out-Null",
    "New-ItemProperty -Path 'HKLM:\\SOFTWARE\\OpenSSH' -Name DefaultShell -Value 'C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe' -PropertyType String -Force | Out-Null",
    "$keyFile = 'C:\\ProgramData\\ssh\\administrators_authorized_keys'",
    "New-Item -ItemType Directory -Path 'C:\\ProgramData\\ssh' -Force | Out-Null",
    `Set-Content -Path $keyFile -Value ${quote(key)} -Encoding ascii`,
    "icacls $keyFile /inheritance:r /grant Administrators:F /grant SYSTEM:F | Out-Null",
    "if ($LASTEXITCODE -ne 0) { throw 'icacls failed' }",
    // A policy set at a more specific scope makes this throw even though LocalMachine was set;
    // with $ErrorActionPreference = 'Stop' that would end the setup before the ready marker.
    "try { Set-ExecutionPolicy -ExecutionPolicy RemoteSigned -Scope LocalMachine -Force } catch [System.Security.SecurityException] { }",
    "Set-Content -Path 'C:\\OEM\\ready.txt' -Value 'ready' -Encoding ascii",
  ]);
  return { installBat, setupPs1 };
}
